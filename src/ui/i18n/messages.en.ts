type MessageKey = keyof typeof messages;
type Placeholders<S extends string> = S extends `${string}{${infer Name}}${infer Rest}` ? Name | Placeholders<Rest> : never;
type Values<K extends MessageKey> = Record<Placeholders<(typeof messages)[K]>, string | number>;

export function t<K extends MessageKey>(
  key: K,
  ...args: Placeholders<(typeof messages)[K]> extends never ? [] : [values: Values<K>]
): string {
  const template = messages[key];
  const values = args[0] as Record<string, string | number> | undefined;
  return values ? template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name])) : template;
}
