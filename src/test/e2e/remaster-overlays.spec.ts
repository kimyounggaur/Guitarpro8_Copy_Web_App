import { expect } from "@playwright/test";
import { clickToolbarControl, focusScore, openApp, state, test } from "./helpers";
import { guitarWithBars } from "./regressions/scoreFixtures";

test("palette pages through results and remembers executed input across a reload", async ({ page }) => {
  await openApp(page, { fixture: guitarWithBars([[5]]) });
  await focusScore(page);
  await page.keyboard.press("Control+e");
  const palette = page.getByRole("dialog", { name: "Command palette" });
  const input = palette.getByRole("textbox");
  const current = palette.locator('[aria-current="true"]');
  const first = await current.textContent();
  await input.press("PageDown");
  expect(await current.textContent()).not.toBe(first);
  await input.press("Home");
  await expect(current).toHaveText(first!);
  await input.fill("add-bar 1");
  await input.press("Enter");
  expect((await state(page)).score.masterBars.length).toBe(2);
  await openApp(page);
  await focusScore(page);
  await page.keyboard.press("Control+e");
  await input.press("ArrowUp");
  await expect(input).toHaveValue("add-bar 1");
  await input.press("ArrowDown");
  await expect(input).toHaveValue("");
});

test("floating stylesheet persists drag and keyboard sizing; Escape dismisses one window", async ({ page }) => {
  await page.setViewportSize({width:1024,height:768});
  await openApp(page, { fixture: guitarWithBars([[5]]) });
  await focusScore(page);
  await page.keyboard.press("F7");
  const frame = page.locator('[data-window-id=style]');
  const title = frame.locator(".remasterWindowTitle");
  const before = (await frame.boundingBox())!;
  const grip = (await title.boundingBox())!;
  await page.mouse.move(grip.x+55,grip.y+15);
  await page.mouse.down();
  await page.mouse.move(grip.x+110,grip.y+45,{steps:5});
  await page.mouse.up();
  await frame.getByRole("button", {name:"Resize Score Stylesheet"}).press("ArrowLeft");
  const after = (await frame.boundingBox())!;
  expect(after.x).toBeGreaterThan(before.x);
  expect(after.width).toBeLessThan(before.width);
  await focusScore(page);
  await page.keyboard.press("Control+e");
  await expect(page.getByTestId("command-palette")).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(frame).toBeVisible();
  await focusScore(page);
  await page.keyboard.press("7");
  expect((await state(page)).score.tracks[0].bars[0].voices[0].beats[0].notes[0].fret).toBe(7);
  await page.keyboard.press("Escape");
  await expect(frame).toHaveCount(0);
  await page.keyboard.press("F7");
  await expect.poll(async () => (await frame.boundingBox())?.x).toBe(after.x);
  await expect.poll(async () => (await frame.boundingBox())?.width).toBe(after.width);
});

test("modal file hub traps Tab and blocks background editing until Escape", async ({ page }) => {
  await openApp(page, { fixture: guitarWithBars([[5]]) });
  await clickToolbarControl(page,"File I/O");
  const modal = page.locator("dialog[data-window-id=file]");
  const close = modal.getByRole("button",{name:"Close File I/O"});
  await close.focus();
  await page.keyboard.press("Shift+Tab");
  await expect(modal.getByRole("button",{name:/Resize/})).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(close).toBeFocused();
  await page.keyboard.press("5");
  await page.keyboard.press("Escape");
  await expect(modal).toHaveCount(0);
});

test("track wizard reviews an instrument before creating exactly one track", async ({ page }) => {
  await openApp(page, { fixture: guitarWithBars([[5]]) });
  await clickToolbarControl(page,/^Add Track/);
  const window = page.locator("dialog[data-window-id=wizard]");
  await window.getByRole("button",{name:"Drums",exact:true}).click();
  await window.getByRole("button",{name:"Next"}).click();
  await expect(window.locator(".instrumentList button").first()).toBeVisible();
  await window.getByRole("button",{name:"Next"}).click();
  await expect(window.getByRole("checkbox", { name: "slash", exact: true })).toBeEnabled();
  await expect(window.getByRole("checkbox", { name: "numbered", exact: true })).toBeDisabled();
  await window.getByRole("textbox",{name:"Name",exact:true}).fill("Lesson Kit");
  await window.getByRole("button",{name:"Next"}).click();
  await expect(window.locator(".wizardSummary")).toContainText("Lesson Kit");
  expect((await state(page)).score.tracks.length).toBe(1);
  await window.getByRole("button",{name:"Create",exact:true}).click();
  await expect.poll(async () => (await state(page)).score.tracks.map((track) => track.name)).toContain("Lesson Kit");
});

test("stylesheet preview resets and applies edits without changing the score during typing", async ({ page }) => {
  await openApp(page, { fixture: guitarWithBars([[5]]) });
  await focusScore(page);
  await page.keyboard.press("F7");
  const style = page.getByRole("region",{name:"Score stylesheet"});
  await style.getByRole("button",{name:"Preview changes"}).click();
  await style.getByLabel("Paper").selectOption("Letter");
  await expect(style.getByLabel("Stylesheet preview")).toBeVisible();
  expect((await state(page)).score.stylesheet.page.paper).toBe("A4");
  await style.getByRole("button",{name:"Reset draft"}).click();
  await expect(style.getByLabel("Paper")).toHaveValue("A4");
  await style.getByLabel("Paper").selectOption("Legal");
  await style.getByRole("button",{name:"Apply",exact:true}).click();
  expect((await state(page)).score.stylesheet.page.paper).toBe("Legal");
  await style.getByRole("button",{name:"Header",exact:true}).click();
  const value = style.getByRole("textbox",{name:"Title",exact:true});
  const before = (await state(page)).revision.revision;
  await value.fill("New lesson title");
  expect((await state(page)).revision.revision).toBe(before);
  await value.press("Enter");
  expect((await state(page)).score.stylesheet.headerFooter.firstPageTitle).toBe("New lesson title");
  await style.getByRole("button",{name:"Preview changes"}).click();
  await value.fill("Discard me");
  await value.press("Enter");
  await style.getByRole("button",{name:"Close stylesheet"}).click();
  const confirm = page.getByRole("dialog",{name:"Unapplied stylesheet changes"});
  await expect(confirm).toBeVisible();
  await confirm.getByRole("button",{name:"Discard and close"}).click();
  expect((await state(page)).score.stylesheet.headerFooter.firstPageTitle).toBe("New lesson title");
});

test("toolbar popup receives Escape before an already open non-modal window", async ({ page }) => {
  await page.setViewportSize({width:1024,height:768});
  await openApp(page, { fixture: guitarWithBars([[5]]) });
  await focusScore(page);
  await page.keyboard.press("F7");
  const style = page.getByRole("region", {name:"Score stylesheet"});
  const more = page.getByRole("button",{name:"More toolbar controls"});
  await more.click();
  const popup = page.locator("#editor-overlays [data-anchored-popover]").last();
  await expect(popup).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(popup).toHaveCount(0);
  await expect(style).toBeVisible();
  await more.click();
  await expect(popup).toBeVisible();
  await style.getByRole("button",{name:"Page",exact:true}).click();
  await expect(popup).toHaveCount(0);
  await expect(style).toBeVisible();
});
